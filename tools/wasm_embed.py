#!/usr/bin/env python3
"""Builds the sample WebAssembly apps and embeds them in the firmware (apps/wasm/wasm_images.c).

  tools/wasm_embed.py snake shooter        (needs tools/wasmbuild.sh's toolchain)

The generated file is committed, so a normal build does not need LLVM.  Each app is installed in flash on the first boot.
"""
import subprocess, sys, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
names = sys.argv[1:] or ["snake", "shooter"]
out = ["/* Generated by tools/wasm_embed.py - do not edit. */", "#include <stdint.h>", ""]
for n in names:
    subprocess.check_call([os.path.join(root, "tools/wasmbuild.sh"), os.path.join(root, "apps/wasm/%s.c" % n)], stdout=subprocess.DEVNULL)
    data = open(os.path.join(root, "apps/wasm/%s.wasm" % n), "rb").read()
    out.append("static const uint8_t img_%s[%d] = {" % (n, len(data)))
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
out += ["", "typedef struct { const char *name; const uint8_t *data; uint32_t size; } wasm_image_t;", "const wasm_image_t g_wasm_images[] = {"]
out += ['    { "%s", img_%s, sizeof img_%s },' % (n, n, n) for n in names]
out += ["};", "const int g_wasm_image_count = %d;" % len(names), ""]
open(os.path.join(root, "apps/wasm/wasm_images.c"), "w").write("\n".join(out))
print("embedded:", ", ".join(names))
