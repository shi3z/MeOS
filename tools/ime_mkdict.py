#!/usr/bin/env python3
"""Builds an input-method dictionary blob (format "IMD1", see drivers/ime/ime_dict.h) from SKK dictionaries.

  tools/ime_mkdict.py -o out.bin  SKK-JISYO.L [more.skk ...]
  tools/ime_mkdict.py --c drivers/ime/ime_mini_dict.c --name ime_mini_dict  tools/ime/mini.skk

SKK files may be UTF-8 or EUC-JP (the ";; -*- coding: ..." header decides).  Annotations after ';' are dropped,
lisp candidates "(concat ...)" and entries whose key is not hiragana (numbers "#", katakana, alphabet) are skipped.
Later files add candidates to earlier ones.  --max-cands limits the candidates kept per key.
"""
import argparse
import re
import struct
import sys

HIRA = re.compile(r'^[ぁ-ゖー]+[a-z]?$')


def read_skk(path):
    raw = open(path, 'rb').read()
    head = raw[:300].decode('ascii', 'ignore')
    enc = 'euc-jp' if 'euc' in head.lower() else 'utf-8'
    text = raw.decode(enc, 'replace')
    entries = {}
    for line in text.splitlines():
        if not line or line.startswith(';') or ' /' not in line:
            continue
        key, rest = line.split(' ', 1)
        if not HIRA.match(key):
            continue
        cands = []
        for c in rest.strip().strip('/').split('/'):
            c = c.split(';', 1)[0].strip()
            if not c or c.startswith('(') or '\\' in c or '�' in c:
                continue
            cands.append(c)
        if cands:
            entries[key] = cands
    return entries


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('files', nargs='+')
    ap.add_argument('-o', '--out')
    ap.add_argument('--c', help='write a C source with the blob as an array instead')
    ap.add_argument('--name', default='ime_dict')
    ap.add_argument('--max-cands', type=int, default=24)
    a = ap.parse_args()

    merged = {}
    for f in a.files:
        for k, cs in read_skk(f).items():
            cur = merged.setdefault(k, [])
            for c in cs:
                if c not in cur:
                    cur.append(c)
    keys = sorted(merged, key=lambda k: k.encode('utf-8'))
    bodies = []
    for k in keys:
        kb = k.encode('utf-8')
        data = b''.join(c.encode('utf-8') + b'\0' for c in merged[k][:a.max_cands])
        if len(kb) > 255 or len(data) > 65535:
            continue
        bodies.append((kb, data))
    count = len(bodies)
    pos = 12 + 4 * count
    offs, blob = [], bytearray()
    for kb, data in bodies:
        offs.append(pos + len(blob))
        blob += bytes([len(kb)]) + kb + struct.pack('<H', len(data)) + data
    total = pos + len(blob)
    out = b'IMD1' + struct.pack('<II', count, total) + b''.join(struct.pack('<I', o) for o in offs) + bytes(blob)
    if a.c:
        with open(a.c, 'w') as f:
            f.write('/* Generated by tools/ime_mkdict.py from %s - do not edit. */\n#include <stdint.h>\n\n' % ', '.join(a.files))
            f.write('const uint8_t %s[%d] = {\n' % (a.name, len(out)))
            for i in range(0, len(out), 24):
                f.write('    ' + ','.join(str(b) for b in out[i:i + 24]) + ',\n')
            f.write('};\nconst uint32_t %s_size = %d;\n' % (a.name, len(out)))
    if a.out:
        open(a.out, 'wb').write(out)
    print('%d keys, %d bytes' % (count, len(out)), file=sys.stderr)


if __name__ == '__main__':
    main()
