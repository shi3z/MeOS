#!/usr/bin/env python3
"""Build a 24px, 16-level coverage atlas; no runtime outline dependency."""
from pathlib import Path
import hashlib,os,struct,tempfile,zlib
from PIL import Image,ImageDraw,ImageFont
from fontTools.ttLib import TTFont
ROOT=Path(__file__).resolve().parents[2]
p=ROOT/'tools/fonts/cache/BIZUDGothic-Regular.ttf'
assert hashlib.sha256(p.read_bytes()).hexdigest()=='7d2b48d84ef4e65c9f85bcf65fb1fb41c92b134be641fab6a7141d597c9a92b0'
tt=TTFont(p);cmap=tt.getBestCmap();f=ImageFont.truetype(str(p),24);data=[]

def encode(font,ch,advance=None):
 x0,y0,x1,y1=font.getbbox(ch,anchor='ls');w=x1-x0;h=y1-y0
 im=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(im).text((-x0,-y0),ch,font=font,anchor='ls',fill=255)
 vals=[(v+8)//17 for v in im.getdata()] if w*h else []
 packed=[(vals[i]<<4)|(vals[i+1] if i+1<len(vals) else 0) for i in range(0,len(vals),2)]
 # Independent 4KiB LZ window per glyph, 3..18-byte matches, 8-token flag groups.
 encoded=[];pos=0;seen={}
 while pos<len(packed):
  flagpos=len(encoded);encoded.append(0);flags=0
  for bit in range(8):
   if pos>=len(packed):break
   key=tuple(packed[pos:pos+3]);prev=-1;length=0
   if len(key)==3:
    # A repeated prefix can have different suffixes. Choose the longest recent
    # match rather than only the last occurrence; the decoder format is unchanged.
    for candidate in reversed(seen.get(key, [])[-32:]):
     if pos-candidate>4095:break
     match=0
     while match<18 and pos+match<len(packed) and packed[candidate+match]==packed[pos+match]:match+=1
     if match>length:prev=candidate;length=match
     if length==18:break
   if length>=3:
    flags|=1<<bit;token=((pos-prev)<<4)|(length-3);encoded.extend([token>>8,token&255]);step=length
   else:encoded.append(packed[pos]);step=1
   for k in range(pos,pos+step):seen.setdefault(tuple(packed[k:k+3]), []).append(k)
   pos+=step
  encoded[flagpos]=flags
 flag=32768
 if len(packed)<=len(encoded):encoded=packed;flag=0
 # Verify every compressed glyph before emitting the firmware asset.
 if flag:
  decoded=[];src=0
  while src<len(encoded) and len(decoded)<len(packed):
   flags=encoded[src];src+=1
   for bit in range(8):
    if len(decoded)>=len(packed):break
    if flags&(1<<bit):
     token=(encoded[src]<<8)|encoded[src+1];src+=2
     back=token>>4
     for _ in range((token&15)+3):decoded.append(decoded[-back])
    else:decoded.append(encoded[src]);src+=1
  assert decoded==packed
 assert w<=64 and h<=64 and len(encoded)<32768
 entry=(len(data),len(encoded)|flag,x0,y0,w,h,round(font.getlength(ch)) if advance is None else advance)
 data.extend(encoded)
 return entry

entries=[]
for cp in sorted(cmap):
 if cp>=32:entries.append((cp,*encode(f,chr(cp))))

# Resolve BIZ UD's OpenType vertical alternates once on the host.  Runtime text
# remains a compact codepoint lookup: no outline, GSUB or shaping engine is
# needed on the Tab5.  vrt2 is a superset of vert in this font.
gsub=tt['GSUB'].table
features={r.FeatureTag:r.Feature for r in gsub.FeatureList.FeatureRecord}
alternates={}
for lookup_index in features['vrt2'].LookupListIndex:
 for subtable in gsub.LookupList.Lookup[lookup_index].SubTable:
  alternates.update(getattr(subtable,'mapping',{}))
vertical=[(cp,alternates[name]) for cp,name in cmap.items() if cp>=32 and name in alternates]
vertical.sort()

# Pillow without libraqm cannot request GSUB by feature.  Give each resolved
# alternate a temporary private-use cmap entry, then rasterize that glyph with
# the exact same FreeType path as the ordinary atlas.
temporary=[]
for n,(cp,glyph) in enumerate(vertical):temporary.append((0xe000+n,cp,glyph))
for table in tt['cmap'].tables:
 if table.isUnicode():
  table.cmap.update({private:glyph for private,_,glyph in temporary
                     if private<=0xffff or table.format in (12,13)})
handle,path=tempfile.mkstemp(suffix='.ttf');os.close(handle)
try:
 tt.save(path);vf=ImageFont.truetype(path,24);upem=tt['head'].unitsPerEm
 vertical_entries=[]
 for private,cp,glyph in temporary:
  advance=max(1,round(tt['vmtx'][glyph][0]*24/upem))
  vertical_entries.append((cp,*encode(vf,chr(private),advance)))
finally:os.unlink(path)

out=ROOT/'drivers/lcd';inc=out/'bizud24_data.inc'
with inc.open('w') as o:
 o.write('/* Generated by tools/fonts/build_bizud.py; BIZ UD Gothic 1.051, SIL OFL 1.1. */\nstatic const biz_glyph glyphs[] = {\n')
 for e in entries:o.write('{'+','.join(map(str,e))+'},\n')
 o.write('};\nstatic const biz_glyph vertical_glyphs[] = {\n')
 for e in vertical_entries:o.write('{'+','.join(map(str,e))+'},\n')
 o.write('};\nstatic const uint8_t coverage[] = {\n')
 for n in range(0,len(data),32):o.write(','.join(map(str,data[n:n+32]))+',\n')
 o.write('};\n')
index=b''.join(struct.pack('<IIHbbBBBx',*e) for e in entries)
vertical_index=b''.join(struct.pack('<IIHbbBBBx',*e) for e in vertical_entries)
coverage=bytes(data)
vertical_offset=(len(coverage)+3)&~3
payload=coverage+b'\0'*(vertical_offset-len(coverage))+vertical_index
payload+=struct.pack('<8sII',b'M5VRT2\0\0',len(vertical_entries),vertical_offset)
asset=ROOT/'assets/fonts/bizud24.m5f';asset.parent.mkdir(parents=True,exist_ok=True)
header=struct.pack('<8sIIIIII',b'M5BIZ24\0',1,len(entries),len(index),len(payload),
                   zlib.crc32(index)&0xffffffff,zlib.crc32(payload)&0xffffffff)
asset.write_bytes(header+index+payload)
print(len(entries),'glyphs +',len(vertical_entries),'vertical alternates;',len(data),
      'coverage bytes;',len(index)+len(payload),'compatible asset bytes')
