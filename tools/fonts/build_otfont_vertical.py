#!/usr/bin/env python3
"""Generate the pinned BIZ UD vrt2 codepoint-to-glyph map for FreeType."""
from pathlib import Path
import hashlib

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "tools/fonts/cache/BIZUDGothic-Regular.ttf"
EXPECTED = "7d2b48d84ef4e65c9f85bcf65fb1fb41c92b134be641fab6a7141d597c9a92b0"
assert hashlib.sha256(FONT.read_bytes()).hexdigest() == EXPECTED

font = TTFont(FONT)
cmap = font.getBestCmap()
gsub = font["GSUB"].table
features = {record.FeatureTag: record.Feature for record in gsub.FeatureList.FeatureRecord}
alternates = {}
for lookup_index in features["vrt2"].LookupListIndex:
    for subtable in gsub.LookupList.Lookup[lookup_index].SubTable:
        alternates.update(getattr(subtable, "mapping", {}))

entries = sorted((cp, font.getGlyphID(alternates[name]))
                 for cp, name in cmap.items() if cp >= 32 and name in alternates)
out = ROOT / "drivers/lcd/otfont_bizud_vertical.inc"
with out.open("w") as handle:
    handle.write("/* Generated by tools/fonts/build_otfont_vertical.py; "
                 "BIZ UD Gothic 1.051, SIL OFL 1.1. */\n")
    handle.write("static const vertical_map_entry bizud_vertical_map[] = {\n")
    for cp, glyph in entries:
        handle.write(f"    {{0x{cp:04x}, {glyph}}},\n")
    handle.write("};\n")
print(f"{len(entries)} BIZ UD vrt2 mappings -> {out.relative_to(ROOT)}")
